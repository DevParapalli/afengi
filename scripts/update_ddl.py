"""Regenerate the per-dialect DDL files from the ORM models -- development only.

Compiles ``CREATE TABLE`` / ``CREATE INDEX`` straight from ``framework/models.py``
via ``CreateTable(...).compile(dialect=...)`` and writes TWO tiers per dialect:

- ``db/<dialect>.sql`` -- DEFAULT no-prefix reference (committed). Read it to see the
  schema without running anything.
- ``db/<dialect>.generated.sql`` -- reflects TABLE_PREFIX / *_TABLE from config at run
  time (gitignored). Apply THIS when deploying.

Prod never issues DDL (see ``init_db`` gating on ``settings.db_auto_create``); these
files are what the DBA runs, so keep them in sync with the models by re-running this
whenever a model changes. No DB connection needed -- compilation is dialect-only.

Run::

    uv run scripts/update_ddl.py
"""

from __future__ import annotations

from pathlib import Path
from typing import cast

from sqlalchemy import Index, Table
from sqlalchemy.dialects import oracle, postgresql
from sqlalchemy.engine.interfaces import Dialect
from sqlalchemy.schema import CreateIndex, CreateTable

# Importing the models registers every table on Base.metadata.
from framework.config import settings
from framework.db import Base
from framework.models import (
    AiModelCallTelemetryRow,
    ApiRequestTelemetryRow,
)

DB_DIR = Path(__file__).resolve().parent.parent / "db"

# request_id (soft-FK) is declared index=True on the model -- its auto index name
# already carries any TABLE_PREFIX (derives from __tablename__). Grab it before the
# explicit Index() calls below mutate the table's .indexes set. cast: the stubs
# type __table__ as FromClause (no .indexes); the runtime object is a Table.
_model_table = cast(Table, AiModelCallTelemetryRow.__table__)

# Telemetry-only indexes, in emitted order. Names are built from the (prefixed)
# __tablename__ so a TABLE_PREFIX flows into the index names too. correlation_id +
# created_at are lookup/report filters. No indexes on the other tables.
INDEXES: list[Index] = [
    next(iter(_model_table.indexes)),  # ix_<prefix>_..._request_id (auto, index=True)
    Index(
        f"ix_{ApiRequestTelemetryRow.__tablename__}_correlation_id",
        ApiRequestTelemetryRow.correlation_id,
    ),
    Index(
        f"ix_{ApiRequestTelemetryRow.__tablename__}_parent_request_id",
        ApiRequestTelemetryRow.parent_request_id,
    ),
    Index(
        f"ix_{ApiRequestTelemetryRow.__tablename__}_created_at",
        ApiRequestTelemetryRow.created_at,
    ),
    Index(
        f"ix_{AiModelCallTelemetryRow.__tablename__}_created_at",
        AiModelCallTelemetryRow.created_at,
    ),
]

_AUTOGEN = (
    "-- AUTO-GENERATED by scripts/update_ddl.py from framework/models.py -- DO NOT EDIT.\n"
    "-- Regenerate: uv run scripts/update_ddl.py"
)

_PG_DESC = (
    "-- PostgreSQL schema for agent-framework (prod: DDL is applied by a DBA, not the app)."
)
_ORA_DESC = "-- Oracle schema for agent-framework (prod: DDL is applied by a DBA, not the app)."

# Oracle-only type-mapping note (appended after the variant note).
_ORA_TYPES = (
    "--\n"
    "-- Type mapping vs PostgreSQL: JSONB -> CLOB (JSON-as-text, see PortableJSON), VARCHAR\n"
    "-- -> VARCHAR2(n CHAR), Uuid -> CHAR(32) (32-hex, no dashes), TIMESTAMPTZ -> DATE."
)

# Two tiers per dialect. <dialect>.sql = committed no-prefix reference (read it to
# see the shape); <dialect>.generated.sql = reflects TABLE_PREFIX / *_TABLE at gen
# time (gitignored), applied when deploying.
_DEFAULT_NOTE = (
    "-- DEFAULT no-prefix reference schema -- read this to see the shape. To DEPLOY with a\n"
    "-- TABLE_PREFIX / *_TABLE override, run the generator and apply <dialect>.generated.sql.\n"
    "-- No partitioning: rows <50k."
)
_GENERATED_NOTE = (
    "-- GENERATED from config at run time -- reflects TABLE_PREFIX / *_TABLE (see config.py).\n"
    "-- The committed <dialect>.sql is the no-prefix default reference. No partitioning: rows <50k."
)


def _header(desc: str, note: str, types: str = "") -> str:
    """Assemble a file header: dialect blurb, autogen banner, default/generated note."""
    parts = [desc, _AUTOGEN, note]
    if types:
        parts.append(types)
    return "\n".join(parts)


INDEX_COMMENT = (
    "-- Telemetry indexes only (lookup/sort paths). request_id = soft-FK join into\n"
    "-- telemetry_api_request.id; correlation_id + created_at = query/report filters."
)


def _strip_prefix(sql: str) -> str:
    """Rewrite prefixed identifiers back to base names so the default files are always
    no-prefix. No-op when TABLE_PREFIX is unset. Index names embed the table name, so
    replacing the table token covers table + index names in one pass."""
    if not settings.table_prefix:
        return sql
    for base in (
        settings.decision_state_table,
        settings.telemetry_api_request_table,
        settings.telemetry_model_call_table,
    ):
        sql = sql.replace(settings.table(base), base)
    return sql


def _clean(sql: str) -> str:
    """Strip outer blanks, expand tabs to 8 spaces, drop trailing whitespace per line."""
    body = sql.strip().expandtabs(8)
    return "\n".join(line.rstrip() for line in body.splitlines())


def _render(header: str, dialect: Dialect) -> str:
    tables = "\n\n".join(
        _clean(str(CreateTable(t).compile(dialect=dialect))) + ";"
        for t in Base.metadata.sorted_tables
    )
    indexes = "\n".join(
        _clean(str(CreateIndex(ix).compile(dialect=dialect))) + ";" for ix in INDEXES
    )
    return f"{header}\n\n{tables}\n\n{INDEX_COMMENT}\n{indexes}\n"


def main() -> int:
    # Each dialect -> (default header, generated header, compiled dialect). The
    # default file is prefix-stripped; the generated file reflects config verbatim.
    dialects = {
        "postgresql": (
            _header(_PG_DESC, _DEFAULT_NOTE),
            _header(_PG_DESC, _GENERATED_NOTE),
            postgresql.dialect(),
        ),
        "oracle": (
            _header(_ORA_DESC, _DEFAULT_NOTE, _ORA_TYPES),
            _header(_ORA_DESC, _GENERATED_NOTE, _ORA_TYPES),
            oracle.dialect(),
        ),
    }
    for name, (default_header, generated_header, dialect) in dialects.items():
        outputs = {
            f"{name}.sql": _strip_prefix(_render(default_header, dialect)),
            f"{name}.generated.sql": _render(generated_header, dialect),
        }
        for fname, content in outputs.items():
            path = DB_DIR / fname
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
